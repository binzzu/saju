export function contextBlock(context, today) {
  return `오늘 날짜(한국): ${today}\n\n[상담자 사주 데이터]\n${context || '(데이터 없음)'}`;
}

export function todayKST(nowMs = Date.now()) {
  return new Date(nowMs + 9 * 3600000).toISOString().slice(0, 10);
}
